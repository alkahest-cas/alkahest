def test_singular_index_is_correct_not_merely_survived(exact_terms):
    """The engineered case: cross-check *through* a singular step.

    ``A(p)`` is reached only by dividing by ``(n+2)³ = p³`` at ``n = p−2``. A
    naive implementation returns a number here; this one has to return the
    *right* number, and the comparison is against exact integer arithmetic.
    """
    terms = exact_terms["apery"]
    rec = ak.ModularRecurrence(*SEQUENCES[0][1:3])
    for p in (5, 7, 11, 13, 17, 19, 23, 29, 31, 101):
        for k in (1, 2, 3, 4):
            for multiple in (1, 2, 3):
                n = multiple * p
                if n >= len(terms):
                    continue
                loss = precision_loss(SEQUENCES[0][1], 0, n, p)
                if p ** (k + loss) >= MAX_MODULUS:
                    continue
                report = rec.evaluate([n], p, k)
                assert report.residues()[0] == terms[n] % p**k, f"A({n}) mod {p}^{k}"
                assert report.n_singular == multiple
                assert report.working_precision == k + loss


def test_a_leading_coefficient_that_vanishes_identically_refuses():
    """``(n−4)·S(n+1) = S(n)`` has no ``S(5)``, at any modulus.

    This is the case no amount of lifting repairs, and the one where a
    ``pow(a, -1, m)``-style implementation raises ``ValueError`` at best and
    returns a residue at worst.
    """
    rec = ak.ModularRecurrence([[-1], [-4, 1]], [1])
    # S(4) = 1/((0−4)(1−4)(2−4)(3−4)) = 1/24; every step up to it is ordinary.
    assert rec.value_mod(4, 7, 3) == pow(24, -1, 7**3)
    with pytest.raises(ak.HolonomicError) as excinfo:
        rec.value_mod(5, 7, 3)
    assert excinfo.value.code == "E-HOLO-007"
    assert "vanishes at n = 4" in str(excinfo.value)


def test_a_sequence_that_leaves_the_p_adic_integers_refuses():
    """``p·S(n+1) = S(n)`` has ``v_p(S(n)) = −n``: no residue exists."""
    rec = ak.ModularRecurrence([[-1], [7]], [1])
    with pytest.raises(ak.HolonomicError) as excinfo:
        rec.value_mod(1, 7, 3)
    assert excinfo.value.code == "E-HOLO-007"
    assert "not a p-adic integer" in str(excinfo.value)


def test_a_singular_step_never_silently_disagrees_with_exact_arithmetic():
    """Brute force over engineered singular recurrences.

    ``(n − c)²·S(n+1) = q(n)·S(n)`` is singular whenever ``p | n − c``. The
    sequence is generated exactly with :class:`fractions.Fraction` and every
    reachable residue compared; anything unreachable must refuse.
    """
    from fractions import Fraction

    rng = random.Random(20260815)
    for _ in range(40):
        c = rng.randrange(0, 12)
        q = [rng.randrange(-9, 10) for _ in range(3)]
        if horner(q, 0) == 0:
            q[0] = 3
        lead = [c * c, -2 * c, 1]  # (n − c)²
        rec = ak.ModularRecurrence([[-x for x in q], lead], [1])

        p = rng.choice([2, 3, 5, 7, 11])
        k = rng.randrange(1, 4)
        limit = 25

        terms = [Fraction(1)]
        undefined_at = None
        for n in range(limit):
            denominator = horner(lead, n)
            if denominator == 0:
                undefined_at = n
                break
            terms.append(Fraction(horner(q, n)) * terms[n] / denominator)

        for target in range(1, len(terms)):
            if undefined_at is not None and target > undefined_at:
                break
            loss = precision_loss([[-x for x in q], lead], 0, target, p)
            value = terms[target]
            # Every term *along the way* has to be a p-adic integer, not just
            # the one asked for: the evaluation walks through all of them, and
            # refuses at the first that is not.
            integral = all(terms[i].denominator % p != 0 for i in range(target + 1))
            reachable = loss is not None and p ** (k + loss) < MAX_MODULUS
            if not (reachable and integral):
                with pytest.raises(ak.HolonomicError):
                    rec.value_mod(target, p, k)
                continue
            want = (value.numerator * pow(value.denominator, -1, p**k)) % p**k
            assert rec.value_mod(target, p, k) == want, (c, q, p, k, target)


def test_out_of_reach_precision_refuses_rather_than_truncating():
    rec = ak.ModularRecurrence(*SEQUENCES[0][1:3])
    with pytest.raises(ak.HolonomicError) as excinfo:
        rec.value_mod(199, 5, 1)
    assert excinfo.value.code == "E-HOLO-008"
    assert "digits of p-adic precision" in str(excinfo.value)
    assert excinfo.value.remediation


