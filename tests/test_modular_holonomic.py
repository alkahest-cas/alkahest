def test_construction_refuses_malformed_recurrences():
    with pytest.raises(ak.HolonomicError) as excinfo:
        ak.ModularRecurrence([[1]], [])
    assert excinfo.value.code == "E-HOLO-004"
    with pytest.raises(ak.HolonomicError):
        ak.ModularRecurrence([[1], [0, 0]], [1])  # zero leading polynomial
    with pytest.raises(ak.HolonomicError):
        ak.ModularRecurrence([[1], [1]], [1, 2])  # wrong number of initial values
    with pytest.raises(TypeError):
        ak.ModularRecurrence([[1], [1]], [0.5])  # a float is not an exact rational
    with pytest.raises(TypeError):
        ak.ModularRecurrence([[1], [1.5]], [1])  # nor is a float coefficient


def test_evaluation_refuses_bad_moduli_and_indices():
    rec = ak.ModularRecurrence(*SEQUENCES[0][1:3])
    for p, k, code in [(9, 2, "E-HOLO-006"), (7, 0, "E-HOLO-006"), (1_000_003, 4, "E-HOLO-006")]:
        with pytest.raises(ak.HolonomicError) as excinfo:
            rec.value_mod(5, p, k)
        assert excinfo.value.code == code
    with pytest.raises(ak.HolonomicError) as excinfo:
        rec.value_mod(-1, 7, 2)
    assert excinfo.value.code == "E-HOLO-004"
    with pytest.raises(ak.HolonomicError):
        rec.values_mod([], 7, 2)


def test_arbitrary_precision_inputs_survive_the_boundary():
    """Coefficients and initial values well past 64 bits."""
    big = 2**200 + 1
    rec = ak.ModularRecurrence([[-big], [big]], [big * 3])
    assert rec.coeffs() == [[-big], [big]]
    assert rec.initial() == [3 * big]
    for p, k in [(7, 4), (101, 3)]:
        assert rec.value_mod(5, p, k) == (3 * big) % p**k


def test_start_offsets_the_index():
    """``start`` names the index that ``initial[0]`` belongs to."""
    terms = central_binomial_terms(60)
    coeffs = SEQUENCES[2][1]
    shifted = ak.ModularRecurrence(coeffs, [terms[10]], start=10)
    assert shifted.start == 10
    for n in (10, 11, 20, 40):
        assert shifted.value_mod(n, 101, 3) == terms[n] % 101**3


def test_accessor_shapes_follow_the_convention():
    """Zero-argument O(1) scalars are properties; collections are methods."""
    rec = ak.ModularRecurrence(*SEQUENCES[0][1:3])
    for name in ("order", "degree", "start", "is_homogeneous"):
        assert not callable(getattr(rec, name)), name
    for name in ("coeffs", "rhs", "initial", "value_mod", "values_mod", "evaluate"):
        assert callable(getattr(rec, name)), name

    report = rec.evaluate([12], 13, 3)
    for name in ("prime", "precision", "working_precision", "modulus", "n_singular", "steps"):
        assert not callable(getattr(report, name)), name
    for name in ("residues", "singular_indices"):
        assert callable(getattr(report, name)), name

    sweep = ak.supercongruence_sweep(rec, [11, 13], k=3, expect=1)
    for name in ("holds", "n_tested", "largest", "claimed_exponent", "sharp", "n_skipped"):
        assert not callable(getattr(sweep, name)), name
    for name in ("residues", "counterexamples", "valuations", "skipped"):
        assert callable(getattr(sweep, name)), name


