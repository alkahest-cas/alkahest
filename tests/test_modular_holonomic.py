@pytest.mark.parametrize(
    ("name", "coeffs", "initial", "_gen"), SEQUENCES, ids=[s[0] for s in SEQUENCES]
)
def test_residues_match_exact_big_integer_arithmetic(name, coeffs, initial, _gen, exact_terms):
    """``S(N) mod p**k`` from the recurrence equals ``S(N) % p**k`` from ``ℤ``.

    Swept over four sequences, seven primes, five precisions and a spread of
    indices. Where the singular steps demand a working modulus past the
    machine-word backend the call must *refuse* with ``E-HOLO-008`` — that is
    checked too, because "returns the right answer or says why not" is the
    property, not "returns the right answer when it feels like it".
    """
    terms = exact_terms[name]
    rec = ak.ModularRecurrence(coeffs, initial)
    order = len(coeffs) - 1
    checked = refused = 0

    for p in (2, 3, 5, 7, 11, 13, 101):
        loss_cache = {}
        for n in (0, 1, 2, 3, 5, 11, 12, 17, 40, 97, 128, 201, 319):
            if n < order:
                continue
            loss = loss_cache.setdefault(n, precision_loss(coeffs, 0, n, p))
            for k in (1, 2, 3, 4, 5):
                if p ** (k + loss) >= MAX_MODULUS:
                    with pytest.raises(ak.HolonomicError) as excinfo:
                        rec.value_mod(n, p, k)
                    assert excinfo.value.code == "E-HOLO-008"
                    refused += 1
                    continue
                got = rec.value_mod(n, p, k)
                assert got == terms[n] % p**k, f"{name}: S({n}) mod {p}^{k}"
                checked += 1

    assert checked > 100, f"{name}: only {checked} residues actually compared"
    # Every sequence here has a leading coefficient that vanishes mod p
    # somewhere, so every one of them exercises the refusal path as well.
    assert refused > 0, f"{name}: the out-of-reach branch was never taken"


def test_a_scattered_index_set_costs_one_pass(exact_terms):
    """``values_mod`` returns the same residues as one ``value_mod`` each."""
    terms = exact_terms["apery"]
    rec = ak.ModularRecurrence(*SEQUENCES[0][1:3])
    indices = [40, 3, 17, 3, 0, 39]
    got = rec.values_mod(indices, 101, 4)
    assert got == [terms[n] % 101**4 for n in indices]
    assert got == [rec.value_mod(n, 101, 4) for n in indices]


def test_evaluation_report_accounts_for_every_lost_digit(exact_terms):
    terms = exact_terms["apery"]
    rec = ak.ModularRecurrence(*SEQUENCES[0][1:3])

    clean = rec.evaluate([12], 13, 3)
    assert clean.residues() == [terms[12] % 13**3]
    assert clean.n_singular == 0
    assert clean.singular_indices() == []
    assert clean.working_precision == clean.precision == 3
    assert clean.modulus == 13**3
    assert clean.prime == 13
    assert clean.steps == 11

    # A(p) crosses n = p−2, where the leading coefficient (n+2)³ is p³.
    crossed = rec.evaluate([13], 13, 3)
    assert crossed.residues() == [terms[13] % 13**3]
    assert crossed.n_singular == 1
    assert crossed.singular_indices() == [11]
    assert crossed.working_precision == 6
    assert crossed.precision == 3


def test_rational_initial_values(exact_terms):
    """Harmonic numbers: a holonomic sequence whose terms are not integers.

    ``(n+1)H(n+1) − (n+1)H(n) = 1``, i.e. ``H(n+1) = H(n) + 1/(n+1)``. Every
    ``H(n)`` for ``n < p`` is a ``p``-adic integer, so the residues are exact;
    ``H(p) = H(p−1) + 1/p`` is not, and the step to it must refuse.
    """
    from fractions import Fraction

    rec = ak.ModularRecurrence([[-1, -1], [1, 1]], [Fraction(0)], rhs=[1])
    assert rec.initial() == [0]
    assert not rec.is_homogeneous
    for p in (7, 11, 13, 101):
        modulus = p**3
        harmonic = Fraction(0)
        for n in range(p):
            if n:
                harmonic += Fraction(1, n)
            expected = (harmonic.numerator * pow(harmonic.denominator, -1, modulus)) % modulus
            assert rec.value_mod(n, p, 3) == expected, f"H({n}) mod {p}^3"
        # H(p) = H(p−1) + 1/p leaves ℤ_p, and is refused rather than reduced.
        with pytest.raises(ak.HolonomicError) as excinfo:
            rec.value_mod(p, p, 3)
        assert excinfo.value.code == "E-HOLO-007"


