def small_primes(limit):
    return [p for p in range(2, limit) if all(p % q for q in range(2, int(p**0.5) + 1))]


def test_apery_supercongruence_sweep():
    """``A(p−1) ≡ 1 (mod p³)`` holds and is sharp; ``mod p⁴`` fails."""
    rec = ak.ModularRecurrence(*SEQUENCES[0][1:3])
    primes = [p for p in small_primes(400) if p >= 5]

    good = ak.supercongruence_sweep(rec, primes, k=3, expect=1)
    assert good.holds
    assert good.n_tested == len(primes)
    assert good.largest == primes[-1]
    assert good.claimed_exponent == 3
    assert good.n_skipped == 0
    assert good.counterexamples() == []
    assert set(good.valuations()) == {3}
    assert good.sharp  # p⁴ is therefore false — see below
    assert "holds" in repr(good)

    bad = ak.supercongruence_sweep(rec, primes, k=4, expect=1, max_counterexamples=3)
    assert not bad.holds
    assert len(bad.counterexamples()) == 3
    assert all(v == 3 for _p, _r, v in bad.counterexamples())
    assert "FAILS" in repr(bad)


def test_sweep_at_a_shifted_index_and_a_prime_dependent_target():
    """``A(p) ≡ A(1) = 5 (mod p³)`` — the Apéry–Beukers congruence at ``n = p``.

    Exercises ``index``, a non-zero ``expect``, and the singular step at
    ``n = p−2`` all at once.
    """
    rec = ak.ModularRecurrence(*SEQUENCES[0][1:3])
    primes = [p for p in small_primes(200) if p >= 5]
    sweep = ak.supercongruence_sweep(rec, primes, k=3, index=lambda p: p, expect=lambda _p: 5)
    assert sweep.holds
    assert sweep.n_tested == len(primes)
    assert sweep.n_skipped == 0


def test_sweep_records_refusals_instead_of_counting_them_as_successes():
    """A prime the evaluation refuses is *skipped*, not silently satisfied."""
    rec = ak.ModularRecurrence(*SEQUENCES[0][1:3])
    # index = 40p forces ~40 singular crossings, which no machine-word modulus
    # survives at these primes.
    sweep = ak.supercongruence_sweep(rec, [5, 7, 11], k=3, index=lambda p: 40 * p)
    assert sweep.n_tested == 0
    assert sweep.n_skipped == 3
    assert all("E-HOLO-008" in reason for _p, reason in sweep.skipped())
    # `holds` on an empty sweep is vacuous, and `sharp` must not claim anything.
    assert sweep.holds
    assert not sweep.sharp


def test_sweep_without_extra_precision_cannot_claim_sharpness():
    rec = ak.ModularRecurrence(*SEQUENCES[0][1:3])
    primes = [p for p in small_primes(100) if p >= 5]
    blunt = ak.supercongruence_sweep(rec, primes, k=3, expect=1, extra_precision=0)
    assert blunt.holds
    assert not blunt.sharp
    assert set(blunt.valuations()) == {3}


def test_sweep_argument_validation():
    rec = ak.ModularRecurrence(*SEQUENCES[0][1:3])
    for kwargs in ({"k": 0}, {"k": 3, "extra_precision": -1}, {"k": 3, "max_counterexamples": 0}):
        with pytest.raises(ValueError):
            ak.supercongruence_sweep(rec, [5], **kwargs)
    with pytest.raises(TypeError):
        ak.supercongruence_sweep(rec, [5], k=3, expect="one")
    with pytest.raises(ak.HolonomicError) as excinfo:
        ak.supercongruence_sweep(rec, [9], k=3)
    assert excinfo.value.code == "E-HOLO-006"


