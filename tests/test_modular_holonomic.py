"""M6 — evaluating a holonomic sequence and a binomial coefficient mod ``p**k``.

The test that matters is the cross-check: every residue this subsystem produces
is compared against the same value computed the slow, obviously-correct way —
build ``S(N)`` as an exact Python integer and reduce it. Anything else here
(speed, refusals, accessors) is secondary to that.

The sequences are built from their *definitions* (sums of binomials), and the
recurrence handed to :class:`alkahest.ModularRecurrence` is checked against
those terms exactly before any residue is compared. A cross-check against a
sequence generated by the same recurrence would only prove the code is
self-consistent.
"""

from __future__ import annotations

import random
import time
from math import comb

import alkahest as ak
import pytest

MAX_MODULUS = 1 << 62


# ---------------------------------------------------------------------------
# The sequences, from their definitions
# ---------------------------------------------------------------------------


def apery_terms(limit):
    """A005259: ``Σ_k C(n,k)² C(n+k,k)²``."""
    return [sum(comb(n, k) ** 2 * comb(n + k, k) ** 2 for k in range(n + 1)) for n in range(limit)]


def motzkin_terms(limit):
    """A001006: ``Σ_k C(n,2k)·Catalan(k)``."""
    return [
        sum(comb(n, 2 * k) * comb(2 * k, k) // (k + 1) for k in range(n // 2 + 1))
        for n in range(limit)
    ]


def central_binomial_terms(limit):
    """A000984: ``C(2n, n)``."""
    return [comb(2 * n, n) for n in range(limit)]


def franel_terms(limit):
    """A000172: ``Σ_k C(n,k)³``."""
    return [sum(comb(n, k) ** 3 for k in range(n + 1)) for n in range(limit)]


# Each entry: name, coefficient polynomials (lowest degree first, one per
# shift), initial values, and the exact-term generator.
SEQUENCES = [
    (
        "apery",
        # (n+2)³A(n+2) − (34n³+153n²+231n+117)A(n+1) + (n+1)³A(n) = 0
        [[1, 3, 3, 1], [-117, -231, -153, -34], [8, 12, 6, 1]],
        [1, 5],
        apery_terms,
    ),
    (
        "motzkin",
        # (n+4)M(n+2) − (2n+5)M(n+1) − (3n+3)M(n) = 0
        [[-3, -3], [-5, -2], [4, 1]],
        [1, 1],
        motzkin_terms,
    ),
    (
        "central_binomial",
        # (n+1)u(n+1) − (4n+2)u(n) = 0
        [[-2, -4], [1, 1]],
        [1],
        central_binomial_terms,
    ),
    (
        "franel",
        # (n+2)²f(n+2) − (7n²+21n+16)f(n+1) − 8(n+1)²f(n) = 0
        [[-8, -16, -8], [-16, -21, -7], [4, 4, 1]],
        [1, 2],
        franel_terms,
    ),
]


def horner(poly, n):
    total = 0
    for c in reversed(poly):
        total = total * n + c
    return total


def valuation(x, p):
    if x == 0:
        raise ValueError("valuation of zero is undefined")
    v = 0
    while x % p == 0:
        x //= p
        v += 1
    return v


def precision_loss(coeffs, start, target, p):
    """Digits of ``p``-adic precision the forward pass to *target* must budget.

    Mirrors what the kernel computes, in obvious Python, so the test knows
    which ``(N, p, k)`` are reachable and which must refuse rather than
    guessing at the boundary.
    """
    order = len(coeffs) - 1
    lead = coeffs[order]
    loss = 0
    for n in range(start, target - order + 1):
        value = horner(lead, n)
        if value == 0:
            return None  # a genuinely undetermined step
        loss += valuation(value, p)
    return loss


@pytest.fixture(scope="module")
def exact_terms():
    return {name: gen(320) for name, _, _, gen in SEQUENCES}


def test_the_recurrences_used_here_are_the_right_ones(exact_terms):
    """The cross-check is worthless if the recurrence is not the sequence's.

    Checked exactly over every term, so a typo in a coefficient fails here
    rather than quietly making both sides of the comparison agree on the wrong
    sequence.
    """
    for name, coeffs, initial, _ in SEQUENCES:
        terms = exact_terms[name]
        order = len(coeffs) - 1
        assert terms[:order] == initial, name
        for n in range(len(terms) - order):
            total = sum(horner(poly, n) * terms[n + i] for i, poly in enumerate(coeffs))
            assert total == 0, f"{name} recurrence fails at n = {n}"


