"""Precompute the Math tab's starter results for the static site.

The hosted playground (GitHub Pages) has no server, so without a local
``python -m alkahest.playground`` the Math tab cannot compute.  So that the
default tab still shows what it does, this script runs the starter cells and
the "More to try" examples through the real translator and sandboxed executor
(``alkahest.playground.service.run_math``, the same code path the local server
uses) and writes the responses to ``src/lib/math-precomputed.json``.  The page
labels them as precomputed and replaces them with live results as soon as a
local server answers.

Run it from the repository with an Alkahest build that has the playground
subpackage, and commit the JSON::

    python demo-playground/web/scripts/precompute-math.py

The cell lists are read from ``src/lib/math-starter.ts`` so they cannot drift.
"""

from __future__ import annotations

import datetime as _dt
import json
import re
import sys
from pathlib import Path

WEB = Path(__file__).resolve().parents[1]
STARTER_TS = WEB / "src" / "lib" / "math-starter.ts"
OUT = WEB / "src" / "lib" / "math-precomputed.json"


def _ts_string_array(source: str, name: str) -> list[str]:
    m = re.search(rf"export const {name}: string\[\] = \[(.*?)\];", source, re.S)
    if not m:
        raise SystemExit(f"could not find {name} in {STARTER_TS}")
    return [s.replace("\\'", "'") for s in re.findall(r"'((?:[^'\\]|\\.)*)'", m.group(1))]


def main() -> int:
    import alkahest
    from alkahest.playground import service

    source = STARTER_TS.read_text(encoding="utf-8")
    starter = _ts_string_array(source, "MATH_STARTER_CELLS")
    examples = _ts_string_array(source, "MATH_MORE_EXAMPLES")

    defs: dict[str, dict] = {}
    starter_out = []
    for text in starter:
        res = service.run_math({"input": text, "definitions": list(defs.values())})
        if res.get("ok") and res.get("definition"):
            d = res["definition"]
            defs.pop(d["name"], None)
            defs[d["name"]] = d
        print(
            f"  {text!r:45} -> {'ok' if res.get('ok') else res.get('error_code')}", file=sys.stderr
        )
        starter_out.append({"input": text, "result": res})

    example_out = {}
    for text in examples:
        res = service.run_math({"input": text, "definitions": []})
        print(
            f"  {text!r:45} -> {'ok' if res.get('ok') else res.get('error_code')}", file=sys.stderr
        )
        example_out[text] = res

    payload = {
        "_comment": "Generated by demo-playground/web/scripts/precompute-math.py — do not edit.",
        "alkahest_version": getattr(alkahest, "__version__", "unknown"),
        "generated": _dt.date.today().isoformat(),
        "starter": starter_out,
        "examples": example_out,
    }
    OUT.write_text(json.dumps(payload, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(WEB.parents[1])}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
