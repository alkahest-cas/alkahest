"""Certificate ledger — a queryable, auditable map of where Lean certification stops.

:attr:`alkahest.DerivedResult.certificate` returns Lean 4 source *sometimes*.
The withhold-rather-than-lie discipline behind that is enforced by an
emit-then-typecheck CI gate (``.github/workflows/lean.yml``), but it leaves a
planning problem: an agent choosing between a fast route and a certifiable one
has no way to know, before spending the compute, which is which.

This module closes that gap with three pieces:

``certifiable(op, *args)``
    A predicate that answers "will this call yield a certificate?" — with a
    *reason* when the answer is no, not a bare ``False``.

:func:`certificate_coverage`
    The per-operation coverage table, **generated by running a corpus** rather
    than hand-maintained (see ``scripts/gen_certificate_ledger.py``), checked
    into the repo as ``certificate_ledger.json``, and pinned by a CI drift
    check. Hand-maintained capability bits are how ``lean_theorem: true`` once
    got advertised for primitives the emitter could not prove; a table that is
    only ever *observed* cannot drift that way without CI noticing.

:func:`require_certificate`
    Fail loudly instead of silently degrading, per call or ambiently via
    ``with alkahest.context(require_certificate=True)``.

Shape classes
-------------
The ledger is keyed by *shape class*: an operation plus a small vector of
structural features of its arguments (which primitive functions occur, whether
they are applied to the bare variable or to a composite, what kind of exponents
appear, and so on). Shape classes are deliberately coarse enough to generalise
to expressions the corpus never saw, and — as the generator verifies — fine
enough that no observed class mixes certified and withheld outcomes.

A class earns the ``certified`` verdict only if *every* corpus observation in it
emitted a certificate. Anything else (``withheld``, ``conditional``,
``partial``, or a class the corpus never reached) makes :func:`certifiable`
answer ``False``. The predicate under-claims by construction.
"""

from __future__ import annotations

import json
import os
from typing import Any

__all__ = [
    "Certifiability",
    "certifiable",
    "certificate_coverage",
    "require_certificate",
]

_LEDGER_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "certificate_ledger.json")

#: Bumped when the shape-class feature vector or the ledger file layout changes.
#: The generator stamps it into the artifact and :func:`_ledger` refuses a file
#: written by an incompatible generator.
SCHEMA_VERSION = 1

# ---------------------------------------------------------------------------
# Operation signatures
#
# Which positional argument carries the expression, which (if any) carries the
# distinguished variable, and whether trailing bounds make the call "definite".
# This is a table of *signatures*, not of outcomes — outcomes are only ever
# observed by running the corpus.
# ---------------------------------------------------------------------------

OPERATIONS: dict[str, dict[str, Any]] = {
    "diff": {"var": 1, "bounds": None},
    "integrate": {"var": 1, "bounds": 2},
    "simplify": {"var": None, "bounds": None},
    "simplify_trig": {"var": None, "bounds": None},
    "simplify_trig_normal_form": {"var": None, "bounds": None},
    "simplify_log_exp": {"var": None, "bounds": None},
    "simplify_egraph": {"var": None, "bounds": None},
    "simplify_expanded": {"var": None, "bounds": None},
    "sum_indefinite": {"var": 1, "bounds": None},
    "sum_definite": {"var": 1, "bounds": 2},
    "product_indefinite": {"var": 1, "bounds": None},
    "product_definite": {"var": 1, "bounds": 2},
}

#: Feature names in the fixed order used to build a shape-class key.
FEATURES = ("form", "funcs", "fn_arg", "mul", "pow", "pow_base", "definite")

_NUMERIC_TAGS = ("integer", "rational", "float")

_TOP_FORM = {
    "symbol": "atom",
    "integer": "atom",
    "rational": "atom",
    "float": "atom",
    "func": "apply",
    "add": "sum",
    "mul": "product",
    "pow": "power",
}

# Ordered from "most certifiable" to "least", so a feature can be summarised
# over a whole expression by keeping the worst case.
_FN_ARG_RANK = {"none": 0, "var": 1, "pow": 2, "other": 3}
_POW_RANK = {"none": 0, "nat": 1, "neg": 2, "frac": 3, "sym": 4}
_MUL_RANK = {"none": 0, "scalar": 1, "general": 2}


# ---------------------------------------------------------------------------
# Shape classification
# ---------------------------------------------------------------------------


def _walk(expr):
    """Yield *expr* and every subexpression, depth-first."""
    yield expr
    node = expr.node()
    tag = node[0]
    if tag == "func":
        for arg in node[2]:
            yield from _walk(arg)
    elif tag in ("add", "mul"):
        for arg in node[1]:
            yield from _walk(arg)
    elif tag == "pow":
        yield from _walk(node[1])
        yield from _walk(node[2])


def _is_var(expr, var) -> bool:
    return var is not None and str(expr) == str(var)


def _is_int_pow_of_var(expr, var) -> bool:
    node = expr.node()
    return node[0] == "pow" and _is_var(node[1], var) and node[2].node()[0] == "integer"


def canonical_expression(expr) -> str:
    """Render *expr* with commutative operands in a fixed order.

    ``str(expr)`` is *not* reproducible across processes: the kernel's ordering
    of ``add``/``mul`` operands depends on a randomly-seeded hash, so the same
    sum can print with its terms swapped from one run to the next. That is
    harmless for a human reading one result, but it would make the ledger's
    example column — and therefore the byte-for-byte CI drift check — a coin
    flip. Sorting commutative operands by their own rendering makes the example
    a stable property of the expression rather than of the run that produced it.
    """
    node = expr.node()
    tag = node[0]
    if tag in ("symbol", "integer", "float"):
        return str(node[1])
    if tag == "rational":
        return f"{node[1]}/{node[2]}"
    if tag == "func":
        return f"{node[1]}({', '.join(canonical_expression(a) for a in node[2])})"
    if tag in ("add", "mul"):
        operands = sorted(canonical_expression(a) for a in node[1])
        separator = " + " if tag == "add" else " * "
        return "(" + separator.join(operands) + ")"
    if tag == "pow":
        return f"{_atom_or_parens(node[1])}^{_atom_or_parens(node[2])}"
    return f"<{tag}>"


def _atom_or_parens(expr) -> str:
    """Render *expr*, parenthesised unless it is a bare symbol or integer.

    Keeps nested powers unambiguous: ``(x^(1/2))^3`` rather than ``x^1/2^3``.
    """
    rendered = canonical_expression(expr)
    if expr.node()[0] in ("symbol", "integer"):
        return rendered
    if rendered.startswith("(") and rendered.endswith(")"):
        return rendered
    return f"({rendered})"


def shape_features(expr, var=None, definite: bool | None = None) -> dict[str, str]:
    """Structural feature vector for one call, used as the ledger key.

    The features are chosen to track the seams the Lean emitter actually has:
    which primitives are involved, whether they are applied pointwise to the
    variable (the fragment ``Real.deriv_*`` covers) or to a composite argument
    (which needs ``HasDerivAt.comp``), whether any exponent is negative or
    fractional (which introduces the ``x ≠ 0`` side conditions the combine
    tactic does not yet thread through), and how the pieces are combined.
    """
    funcs: set[str] = set()
    fn_arg = "none"
    pow_kind = "none"
    pow_base = "none"
    mul_kind = "none"

    for sub in _walk(expr):
        node = sub.node()
        tag = node[0]
        if tag == "func":
            funcs.add(node[1])
            for arg in node[2]:
                if _is_var(arg, var):
                    kind = "var"
                elif _is_int_pow_of_var(arg, var):
                    kind = "pow"
                else:
                    kind = "other"
                if _FN_ARG_RANK[kind] > _FN_ARG_RANK[fn_arg]:
                    fn_arg = kind
        elif tag == "pow":
            exponent = node[2].node()
            if exponent[0] == "integer":
                kind = "nat" if int(exponent[1]) >= 0 else "neg"
            elif exponent[0] in ("rational", "float"):
                kind = "frac"
            else:
                kind = "sym"
            if _POW_RANK[kind] > _POW_RANK[pow_kind]:
                pow_kind = kind
            base = "var" if _is_var(node[1], var) else "expr"
            if pow_base == "none" or base == "expr":
                pow_base = base
        elif tag == "mul":
            non_numeric = [a for a in node[1] if a.node()[0] not in _NUMERIC_TAGS]
            kind = "scalar" if len(non_numeric) <= 1 else "general"
            if _MUL_RANK[kind] > _MUL_RANK[mul_kind]:
                mul_kind = kind

    features = {
        "form": _TOP_FORM.get(expr.node()[0], "other"),
        "funcs": ",".join(sorted(funcs)) or "-",
        "fn_arg": fn_arg,
        "mul": mul_kind,
        "pow": pow_kind,
    }
    # `pow_base` is only meaningful relative to a distinguished variable, and
    # `definite` only for operations that take bounds. Omitting them elsewhere
    # keeps the table free of constant-valued columns.
    if var is not None:
        features["pow_base"] = pow_base
    if definite is not None:
        features["definite"] = "yes" if definite else "no"
    return features


def shape_class(op: str, features: dict[str, str]) -> str:
    """Render *features* as the stable ledger key for *op*."""
    parts = [f"{name}={features[name]}" for name in FEATURES if name in features]
    return "/".join([op, *parts])


def classify(op: str, args, kwargs=None) -> tuple[str, dict[str, str]]:
    """Return ``(shape_class, features)`` for a prospective ``op(*args)`` call.

    Raises
    ------
    ValueError
        If *op* is not a ledger-tracked operation, or the arguments do not
        match its signature.
    """
    from . import DerivedResult, Expr  # local import: avoids a package cycle

    spec = OPERATIONS.get(op)
    if spec is None:
        raise ValueError(
            f"certifiable: unknown operation {op!r}. "
            f"Tracked operations: {', '.join(sorted(OPERATIONS))}"
        )
    kwargs = kwargs or {}
    if not args:
        raise ValueError(f"certifiable: {op} requires at least an expression argument")

    expr = args[0]
    if isinstance(expr, DerivedResult):
        expr = expr.value
    if not isinstance(expr, Expr):
        raise ValueError(f"certifiable: {op} expects an Expr as its first argument")

    var = None
    if spec["var"] is not None and len(args) > spec["var"]:
        candidate = args[spec["var"]]
        if isinstance(candidate, Expr):
            var = candidate

    definite = None
    if spec["bounds"] is not None:
        if len(args) > spec["bounds"]:
            lower = args[spec["bounds"]]
        else:
            # `integrate` names its bounds `a`/`b`; the sum/product family uses
            # `lo`/`hi`. Either may be passed by keyword.
            lower = kwargs.get("a", kwargs.get("lo"))
        definite = lower is not None

    features = shape_features(expr, var, definite)
    return shape_class(op, features), features


