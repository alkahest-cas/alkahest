def require_certificate(result):
    """Return *result* if it carries a Lean certificate; otherwise raise.

    The per-call form of the ambient
    ``with alkahest.context(require_certificate=True)`` mode. Use it to turn a
    silent degradation — a result that quietly arrives without evidence — into
    a loud, coded failure at the point it happens.

    Parameters
    ----------
    result : DerivedResult
        The result to check. Returned unchanged when it certifies, so this
        wraps a call inline.

    Returns
    -------
    DerivedResult

    Raises
    ------
    CertificateUnavailableError
        ``E-CERT-001``, carrying the withholding reason and any blocking
        rewrite rules in its remediation text.

    Example
    -------
    >>> import alkahest as ak
    >>> p = ak.ExprPool(); x = p.symbol("x")
    >>> ak.require_certificate(ak.diff(ak.sin(x), x)).value
    cos(x)

    Ambient form, for a loop that must not produce uncertified claims::

        with ak.context(require_certificate=True):
            claim = ak.integrate(f, x)   # raises E-CERT-001 rather than
                                         # returning an uncertified result
    """
    from . import DerivedResult
    from .exceptions import CertificateUnavailableError

    if not isinstance(result, DerivedResult):
        raise TypeError(f"require_certificate expects a DerivedResult, got {type(result).__name__}")
    if result.certificate is not None:
        return result

    status = result.certificate_status
    blocking = sorted({step["rule"] for step in status["blocking_steps"]})
    if blocking:
        remediation = (
            "No sound Lean encoding exists for rewrite rule(s) "
            f"{', '.join(blocking)}. Use alkahest.certificate_coverage() to find a "
            "certifiable route, or drop the require_certificate requirement."
        )
    elif status["reason"] == "withheld_no_derivation":
        remediation = (
            "The derivation log is empty — the operation changed nothing, so there is "
            "no theorem to certify."
        )
    else:
        remediation = (
            "This shape is outside the certifiable fragment. Use "
            "alkahest.certificate_coverage() to see which shapes certify."
        )
    raise CertificateUnavailableError(
        f"no Lean certificate available for this result ({status['reason']})",
        remediation=remediation,
    )


def certificate_required() -> bool:
    """Return ``True`` when ``context(require_certificate=True)`` is active."""
    from ._context import get_context_value

    return bool(get_context_value("require_certificate", False))
