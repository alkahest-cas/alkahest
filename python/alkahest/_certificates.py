class Certifiability:
    """The answer to "will this call yield a Lean certificate?".

    Truthy exactly when a certificate is (or would be) produced, so it drops
    into ``if certifiable(...):`` — but it carries the *reason*, which is what
    a planning loop actually needs.

    Attributes
    ----------
    certifiable : bool
        The verdict. ``bool(self)`` is the same value.
    operation : str
        The operation asked about.
    shape : str
        Shape-class key (see :func:`certificate_coverage`).
    verdict : str
        Ledger verdict for the shape class: ``"certified"``, ``"withheld"``,
        ``"conditional"``, ``"partial"``, or ``"unknown"`` (never observed).
    reason : str
        Stable reason code. ``"emitted"`` / ``"withheld_no_derivation"`` /
        ``"withheld_uncertifiable_step"`` / ``"withheld_integration_shape"``
        come from actually running the operation; ``"class_certified"`` /
        ``"class_withheld"`` / ``"class_conditional"`` / ``"class_partial"`` /
        ``"unknown_shape"`` come from the ledger alone; ``"operation_failed"``
        means the operation itself raised.
    detail : str
        One-sentence human explanation.
    checked : bool
        ``True`` when the operation was actually run, so the verdict is exact
        rather than predicted.
    result : DerivedResult or None
        The result computed while checking — returned so a caller that goes on
        to use it does not pay for the computation twice.
    error : Exception or None
        The exception raised by the operation, if any.
    evidence : dict or None
        The ledger row backing this answer.
    """

    __slots__ = (
        "certifiable",
        "checked",
        "detail",
        "error",
        "evidence",
        "operation",
        "reason",
        "result",
        "shape",
        "verdict",
    )

    def __init__(
        self,
        *,
        certifiable: bool,
        operation: str,
        shape: str,
        verdict: str,
        reason: str,
        detail: str,
        checked: bool = False,
        result: Any = None,
        error: Exception | None = None,
        evidence: dict[str, Any] | None = None,
    ) -> None:
        self.certifiable = certifiable
        self.operation = operation
        self.shape = shape
        self.verdict = verdict
        self.reason = reason
        self.detail = detail
        self.checked = checked
        self.result = result
        self.error = error
        self.evidence = evidence

    def __bool__(self) -> bool:
        return self.certifiable

    def __repr__(self) -> str:
        return (
            f"Certifiability({self.certifiable}, operation={self.operation!r}, "
            f"reason={self.reason!r}, checked={self.checked})"
        )

    def as_dict(self) -> dict[str, Any]:
        """JSON-serialisable view (omits ``result``, which is not serialisable)."""
        return {
            "certifiable": self.certifiable,
            "operation": self.operation,
            "shape": self.shape,
            "verdict": self.verdict,
            "reason": self.reason,
            "detail": self.detail,
            "checked": self.checked,
            "evidence": self.evidence,
        }


_LEDGER_REASON = {
    "certified": ("class_certified", "every corpus observation of this shape certified"),
    "withheld": ("class_withheld", "no corpus observation of this shape ever certified"),
    "conditional": (
        "class_conditional",
        "this shape certifies only when the operation actually rewrites something; "
        "run it to find out",
    ),
    "partial": (
        "class_partial",
        "corpus observations of this shape disagree, so the answer cannot be predicted",
    ),
}


def certifiable(op, *args, mode: str = "verify", **kwargs) -> Certifiability:
    """Will running *op* on these arguments produce a Lean certificate?

    Parameters
    ----------
    op : str or callable
        Operation name (``"integrate"``) or the function itself
        (``alkahest.integrate``). See :data:`OPERATIONS` for the tracked set.
    *args, **kwargs
        The arguments you would pass to *op*.
    mode : {"verify", "ledger"}
        ``"verify"`` (default) is **sound**: it never answers ``True`` without a
        certificate in hand. It short-circuits to ``False`` for shape classes
        the ledger records as never certifying, and otherwise runs *op* and
        inspects the result — which it hands back on
        :attr:`Certifiability.result`, so the work is not wasted.

        ``"ledger"`` runs nothing at all and answers from the checked-in
        coverage table. Use it for planning across many candidate routes where
        even one evaluation each is too much. Its ``True`` is an empirical
        claim about the shape class, validated against the corpus in CI, not a
        certificate in hand.

    Returns
    -------
    Certifiability
        Truthy iff a certificate is (or would be) produced; carries the reason.

    Examples
    --------
    >>> import alkahest as ak
    >>> p = ak.ExprPool(); x = p.symbol("x")
    >>> bool(ak.certifiable("diff", ak.sin(x), x))
    True
    >>> answer = ak.certifiable("integrate", ak.log(x), x)
    >>> bool(answer), answer.reason
    (False, 'class_withheld')

    Plan a route without computing anything::

        routes = [("integrate", f, x), ("diff", F, x)]
        best = max(routes, key=lambda r: bool(ak.certifiable(*r, mode="ledger")))
    """
    if mode not in ("verify", "ledger"):
        raise ValueError(f"certifiable: mode must be 'verify' or 'ledger', got {mode!r}")

    name = op if isinstance(op, str) else getattr(op, "__name__", None)
    if not isinstance(name, str):
        raise ValueError("certifiable: op must be an operation name or an alkahest function")

    shape, _features = classify(name, args, kwargs)
    row = _ledger()["_index"].get(shape)
    verdict = row["verdict"] if row else "unknown"
    reason, detail = _LEDGER_REASON.get(
        verdict,
        ("unknown_shape", "no corpus observation of this shape class"),
    )

    if mode == "ledger":
        return Certifiability(
            certifiable=verdict == "certified",
            operation=name,
            shape=shape,
            verdict=verdict,
            reason=reason,
            detail=detail,
            evidence=row,
        )

    # Sound mode. A `withheld` class is the one prediction worth trusting
    # without paying for it: answering False costs the caller a certifiable
    # route at worst, and the whole point of the predicate is to under-claim.
    if verdict == "withheld":
        return Certifiability(
            certifiable=False,
            operation=name,
            shape=shape,
            verdict=verdict,
            reason=reason,
            detail=detail,
            evidence=row,
        )

    from . import _context

    try:
        # Suppress an ambient `require_certificate`: asking whether something
        # certifies must never itself raise for the answer being "no". The
        # overlay keeps the caller's pool/domain/assumptions, so the probe runs
        # under exactly the conditions the real call would.
        with _context._overlay(require_certificate=False):
            import alkahest

            result = getattr(alkahest, name)(*args, **kwargs)
    except Exception as exc:
        return Certifiability(
            certifiable=False,
            operation=name,
            shape=shape,
            verdict=verdict,
            reason="operation_failed",
            detail=f"{type(exc).__name__}: {exc}",
            checked=True,
            error=exc,
            evidence=row,
        )

    status = result.certificate_status
    emitted = status["certifiable"]
    if emitted:
        explanation = "certificate emitted"
    elif status["blocking_steps"]:
        blocking = ", ".join(sorted({step["rule"] for step in status["blocking_steps"]}))
        explanation = f"no sound Lean encoding for rewrite rule(s): {blocking}"
    elif status["reason"] == "withheld_no_derivation":
        explanation = "derivation log is empty — nothing to certify"
    else:
        explanation = "the emitter withheld the certificate for this shape"

    return Certifiability(
        certifiable=emitted,
        operation=name,
        shape=shape,
        verdict=verdict,
        reason=status["reason"],
        detail=explanation,
        checked=True,
        result=result,
        evidence=row,
    )


