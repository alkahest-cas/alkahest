_LEDGER_CACHE: dict[str, Any] | None = None


def _ledger() -> dict[str, Any]:
    """Load (and memoise) the generated ledger artifact."""
    global _LEDGER_CACHE
    if _LEDGER_CACHE is None:
        data: dict[str, Any]
        try:
            with open(_LEDGER_PATH, encoding="utf-8") as handle:
                data = json.load(handle)
        except FileNotFoundError:  # pragma: no cover — packaging failure
            data = {"schema_version": SCHEMA_VERSION, "rows": [], "corpus": {}}
        if data.get("schema_version") != SCHEMA_VERSION:  # pragma: no cover
            raise RuntimeError(
                f"certificate_ledger.json has schema_version "
                f"{data.get('schema_version')!r}, expected {SCHEMA_VERSION}. "
                "Regenerate with `python scripts/gen_certificate_ledger.py`."
            )
        data["_index"] = {row["shape"]: row for row in data.get("rows", [])}
        _LEDGER_CACHE = data
    return _LEDGER_CACHE


def certificate_coverage(operation: str | None = None) -> list[dict[str, Any]]:
    """Return the generated per-operation certificate coverage table.

    Each row describes one shape class::

        {
          "operation":    "integrate",
          "shape":        "integrate/form=apply/funcs=log/...",
          "features":     {"form": "apply", "funcs": "log", ...},
          "verdict":      "withheld",
          "observations": {"certified": 0, "withheld": 3, "no_derivation": 0},
          "examples":     ["log(x)", ...],
        }

    ``verdict`` is one of:

    ``certified``
        Every corpus observation of this shape emitted a certificate.
        :func:`certifiable` answers ``True`` here and nowhere else.
    ``withheld``
        No observation emitted; the emitter cannot prove this shape today.
    ``conditional``
        Emits when the operation actually rewrites something, but some
        observations had an empty derivation log (nothing to prove). Not
        predictable from the arguments alone, so :func:`certifiable` answers
        ``False`` with reason ``"class_conditional"``.
    ``partial``
        Mixed certified and withheld observations — the shape class is too
        coarse to separate them. The generator reports these; a healthy tree
        has none.

    Parameters
    ----------
    operation : str, optional
        Restrict to one operation (e.g. ``"diff"``).

    Returns
    -------
    list of dict
        Sorted by ``operation`` then ``shape``.

    Example
    -------
    >>> import alkahest as ak
    >>> withheld = [r for r in ak.certificate_coverage("integrate")
    ...             if r["verdict"] == "withheld"]
    """
    rows = _ledger().get("rows", [])
    if operation is not None:
        rows = [row for row in rows if row["operation"] == operation]
    return [dict(row) for row in rows]


def coverage_summary() -> dict[str, Any]:
    """Aggregate counts over :func:`certificate_coverage`, for ``capabilities()``."""
    ledger = _ledger()
    verdicts: dict[str, int] = {}
    operations: dict[str, dict[str, int]] = {}
    for row in ledger.get("rows", []):
        verdicts[row["verdict"]] = verdicts.get(row["verdict"], 0) + 1
        per_op = operations.setdefault(row["operation"], {})
        per_op[row["verdict"]] = per_op.get(row["verdict"], 0) + 1
    return {
        "schema_version": ledger.get("schema_version"),
        "generated_from": ledger.get("corpus", {}),
        "shape_classes": verdicts,
        "operations": operations,
    }


def certifiable_primitives() -> set[str]:
    """Primitive names whose pointwise derivative ``d/dx f(x)`` certifies.

    Derived from the ledger, so ``capabilities()["primitives"][i]["lean_theorem"]``
    and the coverage table cannot disagree.
    """
    names: set[str] = set()
    for row in _ledger().get("rows", []):
        if row["operation"] != "diff" or row["verdict"] != "certified":
            continue
        features = row["features"]
        if (
            features.get("form") == "apply"
            and features.get("fn_arg") == "var"
            and features.get("pow") == "none"
            and "," not in features.get("funcs", ",")
            and features.get("funcs") != "-"
        ):
            names.add(features["funcs"])
    return names


